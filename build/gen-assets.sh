#!/usr/bin/env bash
#
# gen-assets.sh — regenerate vendor/xt/config/xt-assets.mk from what actually exists.
#
# Why this exists: PRODUCT_PACKAGES entries and PRODUCT_COPY_FILES sources must
# exist at parse time, or `m bacon` dies with "module not found" / "missing file".
# During the design-layer build-out, assets arrive gradually. Hardcoding them in
# xt-common.mk would mean the ROM cannot build until every last font and
# wallpaper is done.
#
# This script inspects the repo, emits only the references that are real, and
# prints what is still missing. Re-run it after adding any asset.
#
set -euo pipefail

SELF="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(dirname "$SELF")"
OUT="$ROOT/config/xt-assets.mk"

cd "$ROOT"

have() { [[ -e "$1" ]]; }
missing=()
lines=()

# ---------------------------------------------------------------------------
# Apps — each must have an Android.bp or Android.mk to be buildable.
# ---------------------------------------------------------------------------
declare -A APPS=(
    [XtThemes]="apps/XtThemes"
    [XtWidgets]="apps/XtWidgets"
    [XtStatus]="apps/XtStatus"
)
pkg_lines=()
for mod in "${!APPS[@]}"; do
    d="${APPS[$mod]}"
    if have "$d/Android.bp" || have "$d/Android.mk"; then
        pkg_lines+=("    $mod")
    else
        missing+=("app $mod ($d/Android.bp or Android.mk)")
    fi
done
if [[ ${#pkg_lines[@]} -gt 0 ]]; then
    lines+=("PRODUCT_PACKAGES += \\")
    lines+=("$(printf '%s \\\n' "${pkg_lines[@]}" | sed '$ s/ \\$//')")
    lines+=("")
fi

# ---------------------------------------------------------------------------
# Fonts — copied to /product/fonts, registered via fonts_customization.xml.
# ---------------------------------------------------------------------------
copy_lines=()
for f in fonts/Doto-VariableFont.ttf fonts/Inter-VariableFont.ttf; do
    if have "$f"; then
        copy_lines+=("    vendor/xt/$f:\$(TARGET_COPY_OUT_PRODUCT)/fonts/$(basename "$f")")
    else
        missing+=("font $f")
    fi
done

# ---------------------------------------------------------------------------
# Artwork — boot animation is the only one the platform requires.
# ---------------------------------------------------------------------------
if have artwork/bootanimation.zip; then
    copy_lines+=("    vendor/xt/artwork/bootanimation.zip:\$(TARGET_COPY_OUT_PRODUCT)/media/bootanimation.zip")
else
    missing+=("artwork artwork/bootanimation.zip (optional; stock animation used)")
fi

if [[ ${#copy_lines[@]} -gt 0 ]]; then
    lines+=("PRODUCT_COPY_FILES += \\")
    lines+=("$(printf '%s \\\n' "${copy_lines[@]}" | sed '$ s/ \\$//')")
    lines+=("")
fi

# ---------------------------------------------------------------------------
# Emit
# ---------------------------------------------------------------------------
{
    echo "#"
    echo "# GENERATED by build/gen-assets.sh — do not edit by hand."
    echo "# Regenerate after adding or removing any app, font, or artwork asset."
    echo "#"
    echo "# Generated: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "#"
    if [[ ${#lines[@]} -eq 0 ]]; then
        echo "# No XT assets present yet — nothing to add."
    fi
    printf '%s\n' "${lines[@]}"
} > "$OUT"

echo "wrote $OUT"
if [[ ${#missing[@]} -gt 0 ]]; then
    echo
    echo "still missing (not referenced, so the build stays green):"
    printf '  - %s\n' "${missing[@]}"
fi
