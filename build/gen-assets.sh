#!/usr/bin/env bash
#
# gen-assets.sh — regenerate vendor/xt/config/xt-assets.mk from what actually exists.
#
# Why this exists: PRODUCT_PACKAGES entries and PRODUCT_COPY_FILES sources must
# exist at parse time, or `m bacon` dies with "module not found" / "missing file".
# During the design-layer build-out, assets arrive gradually. Hardcoding them in
# xt-common.mk would mean the ROM cannot build until every last font and
# wallpaper is done.
#
# This script inspects the repo, emits only the references that are real, and
# prints what is still missing. Re-run it after adding any asset.
#
set -euo pipefail

SELF="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(dirname "$SELF")"
OUT="$ROOT/config/xt-assets.mk"

cd "$ROOT"

have() { [[ -e "$1" ]]; }
missing=()
lines=()

# ---------------------------------------------------------------------------
# Apps — NOT handled here any more.
#
# The three first-party apps now exist in apps/ and are listed directly in
# config/xt-common.mk. Emitting them here as well would add every module to
# PRODUCT_PACKAGES twice. That is not merely untidy: duplicate PRODUCT_PACKAGES
# entries make the product config dump ambiguous and hide the real list, and if
# the two sources ever disagree the fragment silently wins because it is
# -included later.
#
# One owner per fact. xt-common.mk owns the app list; this script owns the
# copy-file assets (fonts, artwork) that depend on binaries we may not have.
#
# Verify the apps still build by checking for their Android.bp, and warn — a
# warning rather than an error, because this script must stay runnable to
# generate the asset fragment even if one app is mid-edit.
# ---------------------------------------------------------------------------
declare -A APPS=(
    [XtThemes]="apps/XtThemes"
    [XtWidgets]="apps/XtWidgets"
    [XtStatus]="apps/XtStatus"
)
for mod in "${!APPS[@]}"; do
    d="${APPS[$mod]}"
    if ! have "$d/Android.bp" && ! have "$d/Android.mk"; then
        missing+=("app $mod has no Android.bp (listed in xt-common.mk)")
    fi
done

# ---------------------------------------------------------------------------
# Fonts — copied to /product/fonts.
#
# Copying the .ttf files alone accomplishes nothing: the platform only sees a
# font if it is declared in a fonts_customization.xml that lives in the same
# directory AND is itself copied to /product/etc/fonts_customization.xml.
# Shipping the files without the registration is a silent no-op — the fonts sit
# on the device, take up space, and are never selectable. Both must be copied
# together, or neither.
# ---------------------------------------------------------------------------
copy_lines=()
font_files=()
for f in fonts/Doto-VariableFont.ttf fonts/Inter-VariableFont.ttf; do
    if have "$f"; then
        copy_lines+=("    vendor/xt/$f:\$(TARGET_COPY_OUT_PRODUCT)/fonts/$(basename "$f")")
        font_files+=("$f")
    else
        missing+=("font $f")
    fi
done

if [[ ${#font_files[@]} -gt 0 ]]; then
    if have fonts/fonts_customization.xml; then
        copy_lines+=("    vendor/xt/fonts/fonts_customization.xml:\$(TARGET_COPY_OUT_PRODUCT)/etc/fonts_customization.xml")
    else
        # Loud, because without it the fonts above are dead weight.
        missing+=("fonts/fonts_customization.xml (fonts are copied but will NOT register)")
    fi
fi

# ---------------------------------------------------------------------------
# Artwork — boot animation is the only one the platform requires.
# ---------------------------------------------------------------------------
if have artwork/bootanimation.zip; then
    copy_lines+=("    vendor/xt/artwork/bootanimation.zip:\$(TARGET_COPY_OUT_PRODUCT)/media/bootanimation.zip")
else
    missing+=("artwork artwork/bootanimation.zip (optional; stock animation used)")
fi

if [[ ${#copy_lines[@]} -gt 0 ]]; then
    lines+=("PRODUCT_COPY_FILES += \\")
    lines+=("$(printf '%s \\\n' "${copy_lines[@]}" | sed '$ s/ \\$//')")
    lines+=("")
fi

# ---------------------------------------------------------------------------
# Emit
# ---------------------------------------------------------------------------
{
    echo "#"
    echo "# GENERATED by build/gen-assets.sh — do not edit by hand."
    echo "# Regenerate after adding or removing any app, font, or artwork asset."
    echo "#"
    echo "# Generated: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "#"
    if [[ ${#lines[@]} -eq 0 ]]; then
        echo "# No XT assets present yet — nothing to add."
    fi
    printf '%s\n' "${lines[@]}"
} > "$OUT"

echo "wrote $OUT"
if [[ ${#missing[@]} -gt 0 ]]; then
    echo
    echo "still missing (not referenced, so the build stays green):"
    printf '  - %s\n' "${missing[@]}"
fi
